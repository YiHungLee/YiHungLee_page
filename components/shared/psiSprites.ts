// 小賽（Psi）的像素圖：12 種表情、8 組循環動作（出自「小賽角色設計」設計稿）
//
// 每個字元是一格像素，座標以身體左上角為原點（身體佔 13 × 12 格，見 PsiBot.tsx）。
// 表情圖 19 × 15 格、原點在 (3, 3)；動作圖 22 × 17 格、原點在 (4, 4)。
// 身體外圍的空白用來放「！」「？」「Z」等符號，畫的時候會超出 SVG 的框。
//
//   '#' 身體（苔綠）   '*' 天線燈與符號（燈橘）   'o' 熄燈、地上的影子
//   '=' 道具（深苔）   '_' 筆電底座               'b' 腮紅
//   't' 淚滴           'p' 書頁                   '.' 空白（眼睛是挖空的格子）

import type { PsiMood } from '../../utils/blogCategories';

export type PsiAction =
  | 'wave'
  | 'hop'
  | 'writing'
  | 'loading'
  | 'idea'
  | 'cheer'
  | 'reading'
  | 'doze';

export interface PsiSprite {
  /** 圖的左上角相對於身體原點的位置 */
  x: number;
  y: number;
  rows: readonly string[];
}

export interface PsiActionSprite {
  label: string;
  /** 一輪的秒數；每格平均分配 */
  seconds: number;
  frames: readonly PsiSprite[];
}

const mood = (rows: string[]): PsiSprite => ({ x: -3, y: -3, rows });
const frame = (rows: string[]): PsiSprite => ({ x: -4, y: -4, rows });

